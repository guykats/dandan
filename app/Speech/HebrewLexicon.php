    public static function vocalize(string $text): string
    {
        // A Hebrew word: letters plus geresh/gershayim (e.g. "ג׳ירפה"), not touching other Hebrew letters.
        return preg_replace_callback(
            '/(?<![\x{05D0}-\x{05EA}\x{05B0}-\x{05C7}])[\x{05D0}-\x{05EA}][\x{05D0}-\x{05EA}׳״]*(?![\x{05D0}-\x{05EA}\x{05B0}-\x{05C7}])/u',
            fn (array $m) => self::WORDS[$m[0]] ?? $m[0],
            $text,
        );
    }

    /** @return array<string, string> */
    public static function words(): array
    {
        return self::WORDS;
    }
